/** Synthetic-only bridge exercising the actual HTML, file and capture exporters. */
import { readFileSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { extractCourseSourcesFromHtml } from "../src/pku-source.js";
import { enrichSourceAttachments } from "../src/pku-attachments.js";
import { toTeachingCaptures, toTeachingAssetManifest } from "../src/pku-teaching.js";

const input = JSON.parse(readFileSync(0, "utf8")) as { folder: string; files: { name: string; mime: string; data: string }[] };
const sources = [];
for (const [i, file] of input.files.entries()) {
  // Filenames are generated by the smoke command, not untrusted HTML or network URLs.
  if (!/^[a-z-]+\.(png|pdf|docx)$/.test(file.name)) throw new Error("synthetic filename required");
  const url = `https://course.pku.edu.cn/bbcswebdav/pid-${i + 1}-dt-content-rid-2/${file.name}`;
  const [source] = extractCourseSourcesFromHtml(`<ul id="content_listContainer"><li id="synthetic-${i}"><div class="item"><h3>Synthetic assignment ${i + 1}</h3></div><div class="details"><p>Complete and submit the attached assignment. The deadline is in the attachment.</p><a href="${url}">${file.name}</a></div></li></ul>`, {
    course: "Synthetic attachment course", section: "课程作业", sourceUrl: "https://course.pku.edu.cn/course?course_id=synthetic", collectedAt: "2026-10-13T12:00:00+08:00",
  });
  sources.push(...await enrichSourceAttachments([source], async () => ({ bytes: Buffer.from(file.data, "base64"), contentType: file.mime }), input.folder));
}
await writeFile(path.join(input.folder, "manifest.json"), JSON.stringify(toTeachingAssetManifest(sources)));
console.log(toTeachingCaptures(sources, "synthetic:files").map(r => JSON.stringify(r)).join("\n"));
